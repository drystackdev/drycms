/**
 * Generates `src/components/file-manager-thumbnails.ts` from the raw SVGs in
 * `src/components/file-icons/`.
 *
 * These are the file-type thumbnails shown in the file manager (folder, pdf,
 * image, ...). Unlike the currentColor icons in icons.tsx, they're full-color
 * illustrations, so they're inlined as base64 data URIs instead of JSX - no
 * bundler processes package assets (see CLAUDE.md), so a plain file path
 * wouldn't be reachable by the browser.
 *
 * Run with: bun run build:file-icons
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const iconsDir = new URL("src/components/file-icons/", root);

const files = readdirSync(fileURLToPath(iconsDir))
  .filter((name) => name.endsWith(".svg"))
  .sort();

const entries = files.map((name) => {
  const stem = name.slice(0, -".svg".length);
  const svg = readFileSync(new URL(name, iconsDir));
  return [stem, `data:image/svg+xml;base64,${svg.toString("base64")}`];
});

const parts = [
  "// Generated by scripts/build-file-icons.mjs - do not edit.",
  "// Source: src/components/file-icons/*.svg. Run `bun run build:file-icons` to regenerate.",
  "",
  "/** File-type thumbnail stem -> base64 data URI. */",
  "export const fileThumbnails = {",
  ...entries.map(([stem, dataUri]) => `\t${JSON.stringify(stem)}: ${JSON.stringify(dataUri)},`),
  "} as const;",
  "",
  "export type FileThumbnailName = keyof typeof fileThumbnails;",
  "",
];

const target = new URL("src/components/file-manager-thumbnails.ts", root);
writeFileSync(fileURLToPath(target), parts.join("\n"));

console.log(`Generated ${entries.length} thumbnails -> ${fileURLToPath(target)}`);
